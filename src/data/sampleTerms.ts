// 오늘의 용어 가져오기
export const getTodayTerm = (date: Date): EconomyTerm => {
  const dayOfYear = Math.floor(
    (date.getTime() - new Date(date.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24)
  );
  const index = dayOfYear % sampleTerms.length;
  return sampleTerms[index];
};

// 특정 용어의 퀴즈 가져오기
export const getQuizByTermId = (termId: string): Quiz | undefined => {
  return sampleQuizzes.find((q) => q.termId === termId);
};

// 특정 용어 관련 기사 가져오기
export const getArticlesByTermId = (termId: string): NewsArticle[] => {
  return sampleArticles.filter((a) => a.termId === termId);
};

// 랜덤 용어 가져오기
export const getRandomTerm = (excludeId?: string): EconomyTerm => {
  const filtered = excludeId ? sampleTerms.filter((t) => t.id !== excludeId) : sampleTerms;
  const index = Math.floor(Math.random() * filtered.length);
  return filtered[index];
};

// 카테고리별 용어 가져오기
export const getTermsByCategory = (category: string): EconomyTerm[] => {
  return sampleTerms.filter((t) => t.category === category);
};
