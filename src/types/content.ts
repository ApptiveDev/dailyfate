// 통합 더미 데이터 생성
export function generateDummyContent(
  type: ContentType,
  date: Date,
): DailyContent {
  const month = date.getMonth() + 1;
  const day = date.getDate();

  // 음력 더미 데이터
  const lunarDate = `2025-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;

  switch (type) {
    case 'fortune':
      return {
        type: 'fortune',
        overview: '오늘은 새로운 시작을 위한 좋은 날입니다.',
        lunarDate,
        fortune: {
          overview:
            '오늘은 새로운 시작을 위한 좋은 날입니다. 긍정적인 에너지가 당신을 감싸고 있으니, 망설이던 일을 시작해보세요.',
          wealth: '예상치 못한 곳에서 재물운이 찾아올 수 있습니다. 충동적인 소비는 자제하세요.',
          love: '소중한 사람과의 대화가 관계를 더욱 깊게 만들어줄 것입니다.',
          success: '꾸준한 노력이 결실을 맺는 시기입니다. 포기하지 말고 끝까지 밀고 나가세요.',
          action: '오늘은 주변 사람들에게 감사의 마음을 전해보세요.',
          lunarDate,
        },
      };

    case 'history': {
      const historyData = generateDummyHistoryData(date);
      return {
        type: 'history',
        overview: `${historyData.year}년 오늘, ${historyData.title}`,
        lunarDate,
        history: historyData,
      };
    }

    case 'idiom': {
      const idiomData = generateDummyIdiomData(date);
      return {
        type: 'idiom',
        overview: `${idiomData.idiom}\n${idiomData.pronunciation}`,
        lunarDate,
        idiom: idiomData,
      };
    }

    case 'motivation': {
      const motivationData = generateDummyMotivationData(date);
      return {
        type: 'motivation',
        overview: `"${motivationData.quote}"\n- ${motivationData.author}`,
        lunarDate,
        motivation: motivationData,
      };
    }

    default:
      return {
        type: 'fortune',
        overview: '오늘의 일력',
        lunarDate,
      };
  }
}
